export function translateDeep(value, dict) {
  if (Array.isArray(value)) return value.map(v => translateDeep(v, dict));
  if (value && typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) out[k] = translateDeep(v, dict);
    return out;
  }
  if (typeof value === 'string') return Object.prototype.hasOwnProperty.call(dict, value) ? dict[value] : value;
  return value;
}

export function localizeReportData(data, lang) {
  const dict = REPORT_I18N[lang];
  if (!dict) return data;
  return translateDeep(data, dict);
}
